const TABLES: Record<Lang, Partial<Record<Key, string>>> = { en, rw, fr };

export function detectLang(): Lang {
  const saved = localStorage.getItem('tendo.clock.lang');
  if (saved === 'en' || saved === 'rw' || saved === 'fr') return saved;
  const nav = (navigator.language || 'en').toLowerCase();
  if (nav.startsWith('rw') || nav.startsWith('kin')) return 'rw';
  if (nav.startsWith('fr')) return 'fr';
  return 'en';
}

export function makeT(lang: Lang) {
  return (key: Key, vars: Record<string, string | number> = {}) => {
    const raw = TABLES[lang][key] ?? en[key];
    return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
  };
}

export type T = ReturnType<typeof makeT>;
